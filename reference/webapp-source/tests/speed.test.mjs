import * as s from "../utils/speed.ts";
let fails = 0; const ok = (n, c) => { if (!c) fails++; console.log(c ? "OK   " : "FEHLER", n); };
const R = (o) => ({ region: "fra1", dbFirstMs: 40, dbMedianMs: 8, claimsFirstMs: 120, claimsNextMs: 1, getUserMs: 12, ...o });
let v = s.interpretSpeed(R({}));
ok("alles gut: zwei grüne Hinweise", v.length === 2 && v.every((x) => x.level === "ok"));
v = s.interpretSpeed(R({ region: "iad1", dbMedianMs: 105, getUserMs: 110, claimsNextMs: 108 }));
ok("USA-Region + 105 ms: rot, nennt fra1 und die Region", v[0].level === "bad" && v[0].text.includes("fra1") && v[0].text.includes("Washington") && v.some((x) => x.title === "Region prüfen"));
ok("Token über das Netz (108 ms): rot mit Hinweis auf Signing Keys", v.find((x) => x.title.startsWith("Anmelde-Prüfung")).level === "bad" && v.some((x) => x.text.includes("Signing Keys")));
v = s.interpretSpeed(R({ dbMedianMs: 40, region: "lhr1" }));
ok("40 ms: gelb", v[0].level === "warn");
v = s.interpretSpeed(R({ dbMedianMs: 8, region: "iad1" }));
ok("Region USA, aber Datenbank schnell: kein falscher Alarm", !v.some((x) => x.title === "Region prüfen") && v[0].level === "ok");
v = s.interpretSpeed(R({ claimsNextMs: 30 }));
ok("30 ms Anmelde-Prüfung: gelb", v.find((x) => x.title.startsWith("Anmelde-Prüfung")).level === "warn");
v = s.interpretSpeed(R({ region: null, dbMedianMs: 3 }));
ok("lokal ohne Region: kein Absturz", v[0].text.includes("unbekannt"));
ok("Grenzen: 25 ms noch grün, 26 gelb, 60 gelb, 61 rot", s.interpretSpeed(R({ dbMedianMs: 25 }))[0].level === "ok" && s.interpretSpeed(R({ dbMedianMs: 26 }))[0].level === "warn" && s.interpretSpeed(R({ dbMedianMs: 60 }))[0].level === "warn" && s.interpretSpeed(R({ dbMedianMs: 61 }))[0].level === "bad");
ok("Median", s.median([5, 1, 3]) === 3 && s.median([1, 2, 3, 4]) === 3 && s.median([]) === 0 && s.median([7]) === 7);
ok("Regionsnamen", s.regionName("fra1") === "Frankfurt" && s.regionName("xyz9") === "xyz9" && s.regionName(null).includes("lokal"));
console.log(fails === 0 ? "\nALLE TESTS BESTANDEN" : `\n${fails} FEHLER`);
process.exit(fails === 0 ? 0 : 1);
